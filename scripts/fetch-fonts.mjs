#!/usr/bin/env node
// Downloads the Vietnamese-capable Google fonts into remotion/fonts/ (woff2 + fonts.css), so preview
// and render (also in Docker without internet) never fall back to a font that lacks "ồ", "ữ"…
// Re-run after changing FAMILIES: node scripts/fetch-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const OUT = path.join(ROOT, 'remotion', 'fonts');
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const SUBSETS = ['vietnamese', 'latin-ext', 'latin'];

// [Google family, axes, names it is registered as]
const FAMILIES = [
  ['Be Vietnam Pro', 'ital,wght@0,400;0,500;0,600;0,700;0,800;0,900;1,700', ['Be Vietnam Pro']],
  ['Inter', 'wght@400;500;600;700;800;900', ['Inter']],
  ['Montserrat', 'ital,wght@0,400;0,700;0,800;0,900;1,700', ['Montserrat']],
  ['Playfair Display', 'ital,wght@0,400;0,700;0,900;1,700;1,900', ['Playfair Display']],
  ['Patrick Hand', 'wght@400', ['Patrick Hand']],
  ['Itim', 'wght@400', ['Itim']],
  // Same look as common system fonts that are missing on the render machine or lack Vietnamese glyphs
  ['Noto Serif', 'ital,wght@0,400;0,700;0,900;1,400;1,700', ['Georgia']],
  ['Arimo', 'ital,wght@0,400;0,700;1,400;1,700', ['Arial', 'Helvetica']],
  ['Tinos', 'ital,wght@0,400;0,700;1,400;1,700', ['Times New Roman', 'Times']],
  ['Anton', 'wght@400', ['Impact']],
  ['Cousine', 'ital,wght@0,400;0,700;1,400;1,700', ['Courier New', 'Courier', 'VN Mono']],
];

fs.mkdirSync(path.join(OUT, 'files'), { recursive: true });
const css = [];
const used = new Set();
for (const [family, axes, names] of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${family.replace(/ /g, '+')}:${axes}&display=block`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${family}: HTTP ${res.status}`);
  const text = await res.text();
  for (const m of text.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face \{([^}]*)\}/g)) {
    const [, subset, body] = m;
    if (!SUBSETS.includes(subset)) continue;
    const src = body.match(/url\((https:[^)]+)\)/)[1];
    const file = `${family.replace(/ /g, '')}-${crypto.createHash('sha1').update(src).digest('hex').slice(0, 10)}.woff2`;
    if (!used.has(file)) {
      used.add(file);
      const dest = path.join(OUT, 'files', file);
      if (!fs.existsSync(dest)) fs.writeFileSync(dest, Buffer.from(await (await fetch(src)).arrayBuffer()));
    }
    for (const n of names) {
      css.push(`/* ${family} · ${subset} */\n@font-face {${body
        .replace(/font-family: '[^']+'/, `font-family: '${n}'`)
        .replace(/url\(https:[^)]+\)/, `url(./files/${file})`)}}`);
    }
  }
  console.log(family, '→', names.join(', '));
}
for (const f of fs.readdirSync(path.join(OUT, 'files'))) if (!used.has(f)) fs.unlinkSync(path.join(OUT, 'files', f));
fs.writeFileSync(path.join(OUT, 'fonts.css'), `/* Generated by scripts/fetch-fonts.mjs — do not edit. */\n${css.join('\n')}\n`);
console.log(`${used.size} files, ${(fs.readdirSync(path.join(OUT, 'files')).reduce((s, f) => s + fs.statSync(path.join(OUT, 'files', f)).size, 0) / 1e6).toFixed(1)} MB`);
